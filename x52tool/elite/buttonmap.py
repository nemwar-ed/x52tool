# Haupt-Hat am Stick (ABS_HAT0X/Y) -> POV1
POV: dict[str, str] = {
    "Joy_POV1Up":    "POV Up",
    "Joy_POV1Right": "POV Right",
    "Joy_POV1Down":  "POV Down",
    "Joy_POV1Left":  "POV Left",
}

AXES: dict[str, str] = {
    "Joy_XAxis":  "Stick X",
    "Joy_YAxis":  "Stick Y",
    "Joy_RZAxis": "Stick Twist",
    "Joy_ZAxis":  "Throttle",
    "Joy_RXAxis": "Rotary 1",
    "Joy_RYAxis": "Rotary 2",
    "Joy_UAxis":  "Slider",
}


def render() -> str:
    lines = [
        '<?xml version="1.0" encoding="UTF-8" ?>',
        f"<!-- {MARKER} – Saitek/Logitech X52 Pro (06A3:0762) -->",
        "<Root>",
        "\t<!-- Buttons -->",
    ]
    for i, name in enumerate(BUTTONS, start=1):
        lines.append(f"\t<Joy_{i}>{escape(name)}</Joy_{i}>")
    lines.append("")
    lines.append("\t<!-- POV Hat -->")
    for tag, name in POV.items():
        lines.append(f"\t<{tag}>{escape(name)}</{tag}>")
    lines.append("")
    lines.append("\t<!-- Axes -->")
    for tag, name in AXES.items():
        lines.append(f"\t<{tag}>{escape(name)}</{tag}>")
        for prefix, suffix in (("Pos_", "+"), ("Neg_", "-")):
            lines.append(f"\t<{prefix}{tag}>{escape(name)} {suffix}</{prefix}{tag}>")
    lines.append("</Root>")
    return "\n".join(lines) + "\n"


class MapState(Enum):
    MISSING = auto()   # keine Datei vorhanden
    OURS = auto()      # von x52tool erzeugt, aktuell
    OUTDATED = auto()  # von x52tool erzeugt, aber aelterer Inhalt
    FOREIGN = auto()   # von jemand anderem (wird beim Installieren gesichert)


@dataclass
class InstallResult:
    written: list[Path]
    backups: list[Path]


def _target_dir(bindings: Path) -> Path:
    return bindings / SUBDIR


def _file_state(path: Path, expected: str) -> MapState:
    try:
        content = path.read_text(encoding="utf-8", errors="replace")
    except FileNotFoundError:
        return MapState.MISSING
    if MARKER not in content:
        return MapState.FOREIGN
    return MapState.OURS if content == expected else MapState.OUTDATED


def state(bindings: Path) -> MapState:
    """Gesamtzustand ueber beide Dateinamen (schlechtester Fall gewinnt)."""
    expected = render()
    states = [_file_state(_target_dir(bindings) / name, expected) for name in FILENAMES]
    for worst in (MapState.FOREIGN, MapState.OUTDATED, MapState.MISSING):
        if worst in states:
            return worst
    return MapState.OURS


def install(bindings: Path) -> InstallResult:
    target = _target_dir(bindings)
    target.mkdir(parents=True, exist_ok=True)
    content = render()
    stamp = time.strftime("%Y%m%d-%H%M%S")
    written: list[Path] = []
    backups: list[Path] = []
    for name in FILENAMES:
        path = target / name
        if _file_state(path, content) is MapState.FOREIGN:
            backup = path.with_name(f"{name}.bak-{stamp}")
            path.rename(backup)
            backups.append(backup)
        path.write_text(content, encoding="utf-8")
        written.append(path)
    return InstallResult(written, backups)


def uninstall(bindings: Path) -> list[Path]:
    """Entfernt nur Dateien, die x52tool selbst erzeugt hat."""
    removed: list[Path] = []
    for name in FILENAMES:
        path = _target_dir(bindings) / name
        if _file_state(path, "") in (MapState.OURS, MapState.OUTDATED):
            path.unlink()
            removed.append(path)
            # Juengste Sicherung einer fremden Datei wiederherstellen
            backups = sorted(path.parent.glob(f"{name}.bak-*"))
            if backups:
                backups[-1].rename(path)
    return removed
