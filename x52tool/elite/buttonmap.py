"""Eigene Tastennamen fuer den X52 Pro in Elite Dangerous.

E:D liest Dateien <Geraet>.buttonMap aus Options/Bindings/DeviceButtonMaps
und zeigt die dort hinterlegten Namen statt "Joy 7" in den Steuerungs-
optionen und in Hinweistexten an. Format (siehe EDCD/EliteCustomButtonNames):

    <?xml version="1.0" encoding="UTF-8" ?>
    <Root>
        <Joy_1>Trigger</Joy_1>
        ...
    </Root>

Dateiname: E:D kennt den X52 Pro als "SaitekX52Pro"; fuer Geraete ohne
eigenen Namen nimmt es VID+PID ("06A30762"). Wir schreiben beide Dateien –
die nicht benutzte wird einfach ignoriert.

Die Joy-Nummern folgen der Reihenfolge, in der das Geraet die Tasten meldet
(identisch mit der Nummerierung im Live-Test, Datei 'buttons' im Repo).
"""

